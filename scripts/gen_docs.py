"""Generate the reference docs that must never go stale: docs/TOOLS.md and docs/ERRORS.md.

    poetry run python scripts/gen_docs.py          # rewrite both files
    poetry run python scripts/gen_docs.py --check  # exit 1 if out of date (the tests do this)

Both files are built from the code (the tool registry and the error table), so a change to a tool or
an error code shows up in the docs by running this script.
"""

# ruff: noqa: E501
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from darkroom_ai.errors import _DEFAULTS
from darkroom_ai.tools.registry import TOOLS, Tool

DOCS = Path(__file__).resolve().parents[1] / "docs"
BANNER = "<!-- Generated by scripts/gen_docs.py from the code. Do not edit by hand. -->\n"


def _type_of(spec: dict[str, Any]) -> str:
    if "enum" in spec:
        return " | ".join(f"`{value}`" for value in spec["enum"])
    if "anyOf" in spec:
        parts = [_type_of(option) for option in spec["anyOf"] if option.get("type") != "null"]
        optional = any(option.get("type") == "null" for option in spec["anyOf"])
        return " or ".join(parts) + (" (may be null)" if optional else "")
    kind = spec.get("type", "any")
    if kind == "array":
        return f"list of {_type_of(spec.get('items', {}))}"
    return str(kind)


def _limits(spec: dict[str, Any]) -> str:
    parts = []
    for key, label in (
        ("minimum", "min"),
        ("maximum", "max"),
        ("minLength", "min length"),
        ("maxLength", "max length"),
        ("minItems", "min items"),
        ("maxItems", "max items"),
    ):
        if key in spec:
            parts.append(f"{label} {spec[key]}")
    return ", ".join(parts)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _first_sentence(text: str) -> str:
    head = text.split(". ")[0].strip()
    return head if head.endswith(".") else head + "."


def tool_section(tool: Tool) -> str:
    schema = tool.schema()["parameters"]
    properties: dict[str, Any] = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = [
        f"### `{tool.name}`",
        "",
        "**Writes** (changes the catalog or a photo's settings)." if tool.writes else "Reads only.",
        "",
        tool.description,
        "",
    ]
    if properties:
        lines += ["| Parameter | Type | Required | Default | Notes |", "|---|---|---|---|---|"]
        for name, spec in properties.items():
            notes = " ".join(part for part in (spec.get("description", ""), _limits(spec)) if part)
            default = "" if name in required or "default" not in spec else f"`{spec['default']}`"
            lines.append(
                f"| `{name}` | {_cell(_type_of(spec))} | {'yes' if name in required else 'no'} "
                f"| {_cell(default)} | {_cell(notes)} |"
            )
    else:
        lines.append("No parameters.")
    return "\n".join(lines) + "\n"


def render_tools() -> str:
    lines = [
        BANNER,
        "# Tool reference",
        "",
        f"{len(TOOLS)} tools, all served by `darkroom mcp`. Every call is validated, journaled once "
        "(also on failure) and returned as JSON. Edit tools work on a virtual copy of the photo, "
        "never the original file, inside the guardrail limits (see `DESIGN.md`).",
        "",
        "| Tool | Kind | What it does |",
        "|---|---|---|",
    ]
    for tool in TOOLS:
        kind = "writes" if tool.writes else "reads"
        lines.append(
            f"| [`{tool.name}`](#{tool.name}) | {kind} | {_cell(_first_sentence(tool.description))} |"
        )
    lines.append("")
    lines += [tool_section(tool) for tool in TOOLS]
    return "\n".join(lines)


def render_errors() -> str:
    lines = [
        BANNER,
        "# Error codes",
        "",
        "Every failure is a `DarkroomError` with a stable code, a plain message and a next step. "
        "Tool results and the CLI show `[CODE] message` and `Next step: ...`. The messages below are "
        "the defaults; a call may add detail. There is no licence logic: Adobe-related messages say "
        "*likely* and point to the Adobe app.",
        "",
        "| Code | Default message | Default next step |",
        "|---|---|---|",
    ]
    for code, (message, step) in sorted(_DEFAULTS.items(), key=lambda item: item[0].value):
        lines.append(f"| `{code.value}` | {_cell(message)} | {_cell(step)} |")
    lines.append("")
    return "\n".join(lines)


def render_all() -> dict[Path, str]:
    return {DOCS / "TOOLS.md": render_tools(), DOCS / "ERRORS.md": render_errors()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the files are out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, text in render_all().items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None
        if current != text:
            stale.append(path.name)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print(f"Out of date: {', '.join(stale)}. Run: poetry run python scripts/gen_docs.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
